#!/usr/bin/env python3
"""Генерирует `ModelAliases.cs` в проектах-потребителях `DashSpec.Core.Model`.

Нужен для миграции ADR-0048: `global using`-алиас перекрывает одноимённый C#-тип,
поэтому потребители начинают видеть F#-IR, а C#-модель становится мёртвой и удаляется.

Запуск из корня репозитория:
    python tools/gen-model-aliases.py            # показать план
    python tools/gen-model-aliases.py --write    # записать файлы
    python tools/gen-model-aliases.py --clean    # удалить сгенерированные файлы
"""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MARKER = "// <auto-generated by tools/gen-model-aliases.py>"

# C#-имя -> полное имя F#-типа (см. design/DASHSPEC-ADR-0048-model-migration-map.md).
EXTRA = {
    "FilterKind": "DashSpec.Modeling.Parse.Filter.FilterKind",
    "SqlDialect": "DashSpec.Modeling.Parse.Document.SqlDialect",
    "DataSourceKind": "DashSpec.Modeling.Parse.DataSource.DataSourceKind",
    "DataSourceSqlCarrier": "DashSpec.Modeling.Parse.DataSource.DataSourceSqlCarrier",
    "LayoutScope": "DashSpec.Modeling.Parse.Layout.LayoutScope",
}


def mapped_types() -> dict[str, str]:
    raw = subprocess.run(
        [sys.executable, str(ROOT / "tools" / "model-shape-diff.py"), "--json"],
        capture_output=True, text=True, check=True,
    ).stdout
    import json

    out = dict(EXTRA)
    for row in json.loads(raw):
        if row.get("fsharp"):
            out[row["cs"]] = row["fsharp"]
    return out


def consumer_projects() -> list[pathlib.Path]:
    found: list[pathlib.Path] = []
    for path in ROOT.rglob("*.csproj"):
        if re.search(r"\\(bin|obj)\\", str(path)):
            continue
        for source in path.parent.rglob("*.cs"):
            if re.search(r"\\(bin|obj)\\", str(source)):
                continue
            if "using DashSpec.Core.Model;" in source.read_text(encoding="utf-8"):
                found.append(path)
                break
    return sorted(found)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--clean", action="store_true")
    args = parser.parse_args()

    projects = consumer_projects()
    print(f"проектов-потребителей: {len(projects)}")
    for project in projects:
        print(f"  {project.relative_to(ROOT)}")

    if args.clean:
        for project in projects:
            target = project.parent / "ModelAliases.cs"
            if target.exists() and MARKER in target.read_text(encoding="utf-8"):
                target.unlink()
                print(f"удалён {target.relative_to(ROOT)}")
        return 0

    types = mapped_types()
    print(f"типов в алиасах: {len(types)}")
    if not args.write:
        return 0

    body = [MARKER, "// C# читает F#-IR напрямую (ADR-0048 / ADR-0103): своей модели не держит.", ""]
    for name in sorted(types):
        body.append(f"global using {name} = {types[name]};")
    body.append("")
    text = "\n".join(body)

    for project in projects:
        target = project.parent / "ModelAliases.cs"
        target.write_text(text, encoding="utf-8")
        print(f"записан {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
